from __future__ import annotations

import json
import sys
import unittest
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

import audit_binary_source as audit


class BinarySourceAuditTest(unittest.TestCase):
    @staticmethod
    def candidate(candidate_id: str, text: str) -> dict[str, object]:
        return {"id": candidate_id, "text": text, "evidenceIds": ["E-1"]}

    def test_multi_target_check_requires_comma_or_standalone_or(self) -> None:
        self.assertEqual(
            ("MULTI_TARGET_CHECK",),
            audit.exclusion_reasons(
                "check", self.candidate("check.one", "Inspect state, then retry."), True
            ),
        )
        self.assertEqual(
            ("MULTI_TARGET_CHECK",),
            audit.exclusion_reasons(
                "check", self.candidate("check.two", "Inspect state or retry."), False
            ),
        )
        self.assertEqual(
            (),
            audit.exclusion_reasons(
                "check", self.candidate("check.three", "Inspect the coordinator."), False
            ),
        )

    def test_probe_placeholder_matches_id_or_exact_phrase(self) -> None:
        self.assertEqual(
            ("PROBE_PLACEHOLDER",),
            audit.exclusion_reasons(
                "cause", self.candidate("cause.probe-one", "Ordinary text."), True
            ),
        )
        self.assertEqual(
            ("PROBE_PLACEHOLDER",),
            audit.exclusion_reasons(
                "check",
                self.candidate("check.one", "Inspect the controlled probe branch."),
                False,
            ),
        )

    def test_positive_evidence_reason_is_only_for_unselected_cause(self) -> None:
        candidate = self.candidate(
            "cause.database.driver-error", "A driver error was captured."
        )
        self.assertEqual(
            ("POSITIVE_EVIDENCE_UNSELECTED",),
            audit.exclusion_reasons("cause", candidate, False),
        )
        self.assertEqual((), audit.exclusion_reasons("cause", candidate, True))
        self.assertEqual((), audit.exclusion_reasons("check", candidate, False))

    def test_hedged_cause_requires_standalone_may(self) -> None:
        self.assertEqual(
            ("HEDGED_CAUSE",),
            audit.exclusion_reasons(
                "cause", self.candidate("cause.one", "The service may be unavailable."), False
            ),
        )
        self.assertEqual(
            (),
            audit.exclusion_reasons(
                "cause", self.candidate("cause.two", "The Mayfly worker stopped."), False
            ),
        )

    def test_reasons_are_overlap_aware_and_deterministic(self) -> None:
        self.assertEqual(
            ("MULTI_TARGET_CHECK", "PROBE_PLACEHOLDER"),
            audit.exclusion_reasons(
                "check",
                self.candidate("check.probe", "Inspect this, or the controlled probe branch."),
                False,
            ),
        )

    def test_conflicting_exact_model_inputs_are_excluded_from_both_classes(self) -> None:
        family_supported = {
            "familyId": "F-1",
            "row": {
                "category": "GENERAL_JAVA",
                "observedExceptionChain": [
                    {
                        "depth": 0,
                        "type": "java.lang.IllegalStateException",
                        "wrapper": False,
                    }
                ],
            },
            "evidenceById": {
                "E-1": {"type": "EXCEPTION_CLASS", "value": "java.lang.IllegalStateException"}
            },
            "kinds": {"check": {"selected": frozenset({"check.same"})}},
        }
        family_not_supported = {
            **family_supported,
            "familyId": "F-2",
            "kinds": {"check": {"selected": frozenset()}},
        }
        candidate = self.candidate(
            "check.same",
            "Check lifecycle and state transitions before the first application frame.",
        )
        pairs = [
            audit.pair_entry(family_supported, "check", candidate),
            audit.pair_entry(family_not_supported, "check", candidate),
        ]
        audit.apply_conflicting_model_input_exclusion(pairs)
        self.assertEqual(
            [("CONFLICTING_MODEL_INPUT_LABEL",), ("CONFLICTING_MODEL_INPUT_LABEL",)],
            [pair["reasons"] for pair in pairs],
        )

    def test_checked_in_report_matches_gate_when_present(self) -> None:
        report_path = ROOT / "reports" / "phase-5-5-1-binary-source-audit.json"
        if not report_path.exists():
            self.skipTest("binary source report is generated by the read-only audit")
        report = json.loads(
            report_path.read_text(encoding="utf-8"),
            object_pairs_hook=audit.source.reject_duplicate_keys,
        )
        self.assertEqual("BINARY_VALIDATION_CLASS_INSUFFICIENT", report["status"])
        self.assertEqual(104, report["splits"]["TRAIN"]["preConflict"]["pairs"])
        self.assertEqual(
            {"SUPPORTED": 58, "NOT_SUPPORTED": 46},
            report["splits"]["TRAIN"]["preConflict"]["labelCounts"],
        )
        self.assertEqual(102, report["splits"]["TRAIN"]["retained"]["pairs"])
        self.assertEqual(
            {"SUPPORTED": 57, "NOT_SUPPORTED": 45},
            report["splits"]["TRAIN"]["retained"]["labelCounts"],
        )
        self.assertEqual(
            64, report["splits"]["TRAIN"]["retained"]["representedFamilies"]
        )
        self.assertEqual(34, report["splits"]["VALIDATION"]["retained"]["pairs"])
        self.assertEqual(
            {"SUPPORTED": 12, "NOT_SUPPORTED": 22},
            report["splits"]["VALIDATION"]["retained"]["labelCounts"],
        )
        self.assertEqual(90, report["familyAggregateReviewCount"])
        self.assertEqual(
            0,
            report["crossSplit"]["conflictingLabelSignatureChecks"]["retained"][
                "modelInputSignature"
            ]["conflictingSignatures"],
        )
        self.assertEqual(
            {
                "candidateText": 9,
                "exactModelInputPair": 4,
                "evidence": 3,
                "throwableTopology": 3,
                "category": 5,
                "exactPairLabelConflicts": 0,
            },
            report["crossSplit"]["retainedLeakageOverlaps"],
        )
        self.assertEqual(29, report["shortcutLeakage"]["uniqueCandidateTexts"])
        self.assertEqual(0, report["shortcutLeakage"]["textsWithBothLabels"])
        self.assertEqual(67, report["shortcutLeakage"]["notSupportedPairs"])
        self.assertEqual(
            [30, 30, 7],
            [
                item["pairs"]
                for item in report["shortcutLeakage"]["notSupportedConcentration"]
            ],
        )
        self.assertFalse(report["methodology"]["ambiguousLabelsForced"])
        self.assertTrue(report["securityCoverage"]["allRequiredCountsZero"])
        self.assertFalse(report["privacy"]["absolutePathsIncluded"])
        self.assertFalse(report["privacy"]["individualLabelsIncluded"])


if __name__ == "__main__":
    unittest.main()
