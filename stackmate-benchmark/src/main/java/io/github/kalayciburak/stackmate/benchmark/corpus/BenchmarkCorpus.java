    public static List<GroundTruthCase> cases() {
        return CASES;
    }

    private static GroundTruthCase typeCase(
            String caseId,
            BenchmarkDomain domain,
            DiagnosticCategory category,
            String rootType,
            String causeId,
            String checkId,
            String scenarioFactoryKey) {
        return new GroundTruthCase(
                caseId,
                domain,
                category,
                rootType,
                List.of(new ExpectedEvidenceFact(EvidenceType.EXCEPTION_CLASS, rootType)),
                List.of(causeId),
                List.of(checkId),
                COMMON_FORBIDDEN_CLAIMS,
                scenarioFactoryKey);
    }

    private static GroundTruthCase sqlCase(
            String caseId, String sqlState, DiagnosticCategory category, String diagnosisSlug) {
        return new GroundTruthCase(
                caseId,
                BenchmarkDomain.JDBC_PERSISTENCE,
                category,
                "java.sql.SQLException",
                List.of(
                        new ExpectedEvidenceFact(
                                EvidenceType.EXCEPTION_CLASS, "java.sql.SQLException"),
                        new ExpectedEvidenceFact(EvidenceType.SQL_STATE, sqlState)),
                List.of("cause.database." + diagnosisSlug, "cause.database.driver-error"),
                List.of("check.database." + diagnosisSlug, "check.database.driver-error"),
                COMMON_FORBIDDEN_CLAIMS,
                caseId);
    }
